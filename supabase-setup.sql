-- Run this script in Supabase Dashboard > SQL Editor for project ffthwgjczgfzenqzzhto.
-- It creates the appointment table and permits public form submissions only.
-- It does NOT permit anonymous visitors to read appointment records.

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  full_name text not null,
  district text not null,
  phone text not null,
  national_id text not null,
  appointment_date date not null,
  created_at timestamptz not null default now()
);

alter table public.appointments enable row level security;

grant insert on table public.appointments to anon, authenticated;
grant usage, select on sequence public.appointments_id_seq to anon, authenticated;

drop policy if exists "Allow public appointment submissions" on public.appointments;
create policy "Allow public appointment submissions"
on public.appointments
for insert
to anon, authenticated
with check (
  length(trim(full_name)) > 0
  and length(trim(district)) > 0
  and length(trim(phone)) > 0
  and length(trim(national_id)) > 0
  and appointment_date >= current_date
);
